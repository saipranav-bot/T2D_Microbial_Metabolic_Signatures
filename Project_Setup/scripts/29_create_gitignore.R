".Ruserdata",


"# ===============================",
"# R package cache",
"# ===============================",

"renv/library/",
"packrat/lib/",


"# ===============================",
"# Temporary files",
"# ===============================",

"*.tmp",
"*.log",
"*.bak",


"# ===============================",
"# Large sequencing / microbiome data",
"# ===============================",

"data/raw/",
"*.fastq",
"*.fq",
"*.bam",
"*.sam",
"*.vcf",


"# ===============================",
"# Intermediate files",
