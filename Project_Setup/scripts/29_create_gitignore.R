"cache/",


"# ===============================",
"# OS files",
"# ===============================",

".DS_Store",
"Thumbs.db",


"# ===============================",
"# Large R objects",
"# Keep final objects only",
"# ===============================",

"*.rds",
"*.RData",


"# ===============================",
